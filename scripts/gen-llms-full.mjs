#!/usr/bin/env node
/**
 * Generates llms-full.txt — AGENTS.md + the Game contract + guides concatenated
 * into one file, so an LLM can load Luca's whole "how to build a game" context
 * in a single fetch. Run: npm run llms:full  (re-run when the source docs change).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

const PARTS = [
  'AGENTS.md',
  'docs/GAME_DEFINITION.md',
  'docs/guide/getting-started.md',
  'docs/guide/concepts.md',
  'docs/guide/your-first-game.md',
  'docs/GESTURE_ALGORITHM.md',
  'docs/COMPLETION_API.md',
]

let out =
  '# Luca — full docs bundle for LLMs\n\n' +
  '> Auto-generated by scripts/gen-llms-full.mjs (`npm run llms:full`). Do not edit by hand.\n' +
  '> Project: https://github.com/MaggieMaomao/luca — see llms.txt for the map.\n'

for (const p of PARTS) {
  try {
    out += `\n\n---\n\n<!-- source: ${p} -->\n\n` + readFileSync(join(root, p), 'utf8').trim() + '\n'
  } catch {
    console.warn('skip (missing):', p)
  }
}

writeFileSync(join(root, 'llms-full.txt'), out)
console.log(`wrote llms-full.txt (${out.length} bytes, ${PARTS.length} sources)`)
